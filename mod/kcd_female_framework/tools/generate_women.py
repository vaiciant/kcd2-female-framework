def find_female(name):
    node = female.find(f".//*[@Name='{name}']")
    if node is None:
        raise SystemExit(f"Not in the Female branch: {name}")
    return node


def male_branch(*names):
    node = male
    for name in names:
        node = node.find(f"DerivedComponents/*[@Name='{name}']")
    return node


def chain(node):
    """The ancestors of a node under Female, without Female itself, and the node at the end."""
    result = []
    while node is not female:
        if node.tag != "DerivedComponents":
            result.insert(0, node)
        node = parents[node]
    return result


def without_children(node):
    clone = ET.Element(node.tag, node.attrib)
    clone.extend(copy.deepcopy(child) for child in node if child.tag != "DerivedComponents")
    return clone


def attach(parent, node):
    """Hangs a node from its parent, or returns the one that was already there with that name."""
    children = parent.find("DerivedComponents")
    if children is None:
        children = ET.SubElement(parent, "DerivedComponents")
    for child in children:
        if child.tag == node.tag and child.get("Name") == node.get("Name"):
            return child
    children.append(node)
    return node


def with_prefix(name):
    """The name of the piece in the mod: the game's without its f_ or F_, with the women's prefix."""
    return PREFIX + re.sub(r"^[fF]_", "", name)


def prepare(node, kind):
    """Sets the prefix and points the meshes to the fitted ones, which are noted down to generate them."""
    for child in node.iter():
        if child.get("Name") and child.tag in ("Head", "Hair", "Body", "Clothing"):
            child.set("Name", with_prefix(child.get("Name")))
        for field in ("Model", "SimBinding"):
            path = child.get(field)
            if path and path != "dummy":
                meshes.add((kind, path))
                child.set(field, f"../../{PREFIX}woman/{kind}/{path}")
    return node


def without_physics(node):
    """Hair: the braids have untested bones."""
    for elements in node.iter("Elements"):
        for element in elements.findall("JointElement"):
            elements.remove(element)
    return node


def without_simulation(node):
    """Simulated cloth does not follow the legs in first person: it stays stuck to the hips and thighs, like the smock."""
    for elements in node.iter("Elements"):
        for element in elements.findall("VClothElement"):
            elements.remove(element)
            if element.get("Model") or element.get("Material"):
                ET.SubElement(elements, "SkinElement", {
                    field: element.get(field) for field in ("EquipmentPart", "BodyLayerId", "Model", "Material") if element.get(field) is not None
                })
    return node



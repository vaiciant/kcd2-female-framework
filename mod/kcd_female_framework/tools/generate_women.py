def chunks(data):
    signature, version, count, table = struct.unpack_from("<4sIII", data, 0)
    if signature != b"CrCh" or version != 0x746:
        raise SystemExit(f"Unsupported format: {signature!r} {version:#x}")
    return [struct.unpack_from("<HHIII", data, table + i * 16) for i in range(count)]


def bones(data):
    """Name, position and parent of each bone. Each bone takes 584 bytes, after a 32-byte header."""
    for kind, _, _, size, offset in chunks(data):
        if kind == CHUNK_BONES:
            bone_list = []
            for i in range((size - 32) // 584):
                base = offset + 32 + i * 584
                matrix = struct.unpack_from("<12f", data, base + 264)
                parent = struct.unpack_from("<i", data, base + 572)[0]
                name = data[base + 312:base + 568].split(b"\0")[0].decode("latin1")
                bone_list.append((name, (matrix[3], matrix[7], matrix[11]), i + parent if parent else -1))
            return bone_list
    raise SystemExit("No bone table")


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def unit(a, b):
    diff = [x - y for x, y in zip(a, b)]
    length = sum(x * x for x in diff) ** 0.5
    return [x / length for x in diff]


def translation(delta):
    return lambda p: [x + y for x, y in zip(p, delta)]


def rotation(source, target, source_tip, target_tip):
    """Takes a joint to its place, and rotates what hangs from it so that it points as in the other skeleton."""
    a, b = unit(source_tip, source), unit(target_tip, target)
    axis = cross(a, b)
    cosine = sum(x * y for x, y in zip(a, b))
    factor = (1 - cosine) / max(sum(x * x for x in axis), 1e-12)

    def move_point(p):
        v = [x - y for x, y in zip(p, source)]
        one = cross(axis, v)
        two = cross(axis, one)
        return [h + x + y + z * factor for h, x, y, z in zip(target, v, one, two)]

    return move_point


def displacements(bone_list, man, woman):
    """How what hangs from each bone of a mesh moves, from the woman's skeleton to the man's."""

    def own(name):
        delta = tuple(a - b for a, b in zip(man[name], woman[name]))
        side = name.removeprefix("Left").removeprefix("Right")
        return (delta[0] * ARM_WIDTH.get(side, 1), delta[1], delta[2])

    def mean(a, b):
        return tuple((x + y) / 2 for x, y in zip(own(a), own(b)))

    # The whole head moves together. Spine4 and the clavicles are somewhere else in each skeleton: they take the value
    # of their neighbours.
    head = own("Head")
    neighbours = {
        "Spine4": mean("Spine3", "Neck"),
        "LeftShoulder": mean("Neck", "LeftArm"),
        "RightShoulder": mean("Neck", "RightArm"),
    }
    result = []
    for name, _, parent in bone_list:
        finger = FINGER.match(name)
        if finger:
            tip = f"{finger[1]}Hand{finger[2]}{int(finger[3]) + 1}"
            if name in man and name in woman and tip in man and tip in woman:
                result.append(rotation(woman[name], man[name], woman[tip], man[tip]))
                continue
        lineage = [name]
        while parent >= 0:
            lineage.append(bone_list[parent][0])
            parent = bone_list[parent][2]
        if "Head" in lineage:
            result.append(translation(head))
            continue
        for current in lineage:
            if current in neighbours:
                result.append(translation(neighbours[current]))
                break
            if current in man and current in woman:
                result.append(translation(own(current)))
                break
        else:
            result.append(translation((0.0, 0.0, 0.0)))
    return result


def move(position, ids, weights, table, skirt):
    total = sum(weights)
    moved = [0.0, 0.0, 0.0]
    for bone, weight in zip(ids, weights):
        if weight:
            moved = [x + y * weight / total for x, y in zip(moved, table[bone](position))]
    moved[0] *= 1 + skirt * min(max((HIPS - moved[2]) / (HIPS - HEM), 0), 1)
    return moved


def hidden(kind, path):
    """Which heights are hidden in first person: the head and what is worn on it."""
    if kind in ("head", "hair"):
        return lambda height: height > HIDDEN_HEIGHT
    if kind == "clothing" and path.startswith("f_head/"):
        return lambda height: True
    return None


def read_streams(data):
    streams = {}
    for kind, _, _, _, offset in chunks(data):
        if kind == CHUNK_DATA_STREAM:
            _, stream, count, width = struct.unpack_from("<4I", data, offset)
            streams[stream] = (offset + 24, count, width)
    return streams


def with_color(data):
    """Adds the color stream that the groups need, all on. It goes after the positions one."""
    entries = chunks(data)
    chunk_bodies = {entry: data[entry[4]:entry[4] + entry[3]] for entry in entries}
    positions_entry = next(e for e in entries if e[0] == CHUNK_DATA_STREAM and struct.unpack_from("<I", data, e[4] + 4)[0] == STREAM_POSITION)
    count = read_streams(data)[STREAM_POSITION][1]
    header = bytearray(chunk_bodies[positions_entry][:24])
    struct.pack_into("<4I", header, 0, 0, STREAM_COLOR, count, 4)
    new_entry = (CHUNK_DATA_STREAM, positions_entry[1], max(e[2] for e in entries) + 1, 24 + count * 4, positions_entry[4] + 1)
    chunk_bodies[new_entry] = bytes(header) + bytes([255]) * (count * 4)
    mesh_entry = next(e for e in entries if e[0] == CHUNK_MESH)
    chunk = bytearray(chunk_bodies[mesh_entry])
    struct.pack_into("<i", chunk, MESH_STREAMS + STREAM_COLOR * 4, new_entry[2])
    chunk_bodies[mesh_entry] = bytes(chunk)
    return rebuild(entries + [new_entry], chunk_bodies)


def fit(data, man, woman, hide, skirt):
    if hide and STREAM_COLOR not in read_streams(data):
        data = with_color(data)
    out = bytearray(data)
    table = displacements(bones(data), man, woman)
    streams = read_streams(data)
    positions, count, _ = streams[STREAM_POSITION]
    bone_map, _, width = streams[STREAM_WEIGHTS]
    fmt = "<4H4B" if width == 12 else "<4B4B"
    new_positions = []
    for i in range(count):
        position = struct.unpack_from("<3f", data, positions + i * 12)
        values = struct.unpack_from(fmt, data, bone_map + i * width)
        moved = move(position, values[:4], values[4:], table, skirt)
        struct.pack_into("<3f", out, positions + i * 12, *moved)
        new_positions.append(moved)
        if hide and STREAM_COLOR in streams and hide(moved[2]):
            out[streams[STREAM_COLOR][0] + i * 4 + 3] &= 0xFE

    for kind, _, _, size, offset in chunks(data):
        if kind == CHUNK_VERTICES:
            for i in range((size - 32) // 64):
                base = offset + 32 + i * 64
                position = struct.unpack_from("<3f", data, base + 12)
                ids = struct.unpack_from("<4H", data, base + 36)
                weights = struct.unpack_from("<4f", data, base + 44)
                struct.pack_into("<3f", out, base + 12, *move(position, ids, weights, table, skirt))
        elif kind == CHUNK_MESH:
            minimum = [min(p[axis] for p in new_positions) for axis in range(3)]
            maximum = [max(p[axis] for p in new_positions) for axis in range(3)]
            struct.pack_into("<6f", out, offset + 108, *minimum, *maximum)
    return bytes(out), min(p[2] for p in new_positions), max(p[2] for p in new_positions)


def parts_by_bone(data):
    """The part of each vertex, by its bone with the most weight."""
    streams = read_streams(data)
    names = [name for name, _, _ in bones(data)]
    bone_map, count, width = streams[STREAM_WEIGHTS]
    fmt = "<4H4B" if width == 12 else "<4B4B"
    result = []
    for i in range(count):
        values = struct.unpack_from(fmt, data, bone_map + i * width)
        name = names[values[values[4:].index(max(values[4:]))]]
        result.append(next(part for part, pattern in BODY_PARTS.items() if pattern.match(name)))
    return result


def parts_by_height(data):
    positions, count, _ = read_streams(data)[STREAM_POSITION]
    return ["top" if struct.unpack_from("<3f", data, positions + i * 12)[2] > WAIST else "skirt" for i in range(count)]


def rebuild(entries, chunk_bodies):
    """The file with these chunks, in their order and aligned to 4 bytes."""
    out = bytearray(16 + 16 * len(chunk_bodies))
    struct.pack_into("<4sIII", out, 0, b"CrCh", 0x746, len(chunk_bodies), 16)
    new_offsets = {}
    for entry in sorted(chunk_bodies, key=lambda e: e[4]):
        out.extend(b"\0" * (-len(out) % 4))
        new_offsets[entry] = len(out)
        out.extend(chunk_bodies[entry])
    for order, entry in enumerate(e for e in entries if e in chunk_bodies):
        struct.pack_into("<HHIII", out, 16 + order * 16, entry[0], entry[1], entry[2], len(chunk_bodies[entry]), new_offsets[entry])
    return bytes(out)


def skirt_weight(position, bone_names, man):
    """Bone and weight of a skirt vertex: the hips at the top and, towards the hem, the thigh of its side."""
    right = man["RightUpLeg"][0]
    side = min(max((position[0] - right) / (man["LeftUpLeg"][0] - right), 0), 1)
    down = THIGH_SHARE * min(max((HIPS - position[2]) / (HIPS - SKIRT_KNEE), 0), 1)
    return [(bone_names.index("Hips"), 1 - down), (bone_names.index("LeftUpLeg"), down * side), (bone_names.index("RightUpLeg"), down * (1 - side)), (0, 0.0)]


def without_cloth(data, body, man):
    """The same mesh with the bone list of the body. What weighed on cloth bones goes to skirt_weight."""
    old_names = [name for name, _, _ in bones(data)]
    new_names = [name for name, _, _ in bones(body)]
    if {name for name in old_names if not name.startswith(CLOTH_BONE)} != set(new_names):
        raise SystemExit("The smock does not have the bones of the body")
    equivalent = {i: new_names.index(name) for i, name in enumerate(old_names) if not name.startswith(CLOTH_BONE)}

    def weigh(position, ids, weights):
        if any(weight and i not in equivalent for i, weight in zip(ids, weights)):
            return skirt_weight(position, new_names, man)
        return [(equivalent.get(i, 0), weight) for i, weight in zip(ids, weights)]

    out = bytearray(data)
    streams = read_streams(data)
    positions, count, _ = streams[STREAM_POSITION]
    bone_map, _, width = streams[STREAM_WEIGHTS]
    for i in range(count):
        values = struct.unpack_from("<4H4B", data, bone_map + i * width)
        result = weigh(struct.unpack_from("<3f", data, positions + i * 12), values[:4], [v / 255 for v in values[4:]])
        ints = [round(weight * 255) for _, weight in result]
        ints[0] += 255 - sum(ints)
        struct.pack_into("<4H4B", out, bone_map + i * width, *(bone for bone, _ in result), *ints)

    entries = chunks(data)
    body_chunks = {entry[0]: entry for entry in chunks(body)}
    chunk_bodies = {}
    for entry in entries:
        kind, _, _, size, offset = entry
        if kind in (CHUNK_BONES, CHUNK_PHYSICAL_BONES):
            _, _, _, body_size, body_offset = body_chunks[kind]
            chunk_bodies[entry] = body[body_offset:body_offset + body_size]
            continue
        chunk = bytearray(out[offset:offset + size])
        if kind == CHUNK_BONE_BOXES:
            bone = struct.unpack_from("<I", chunk, 0)[0]
            if bone not in equivalent:
                continue
            struct.pack_into("<I", chunk, 0, equivalent[bone])
        elif kind == CHUNK_VERTICES:
            for i in range((size - 32) // 64):
                base = 32 + i * 64
                result = weigh(struct.unpack_from("<3f", chunk, base + 12), struct.unpack_from("<4H", chunk, base + 36), struct.unpack_from("<4f", chunk, base + 44))
                struct.pack_into("<4H4f", chunk, base + 36, *(bone for bone, _ in result), *(weight for _, weight in result))
        chunk_bodies[entry] = bytes(chunk)
    return rebuild(entries, chunk_bodies)


def mark_bit(data, bit, is_off):
    """Sets the alpha bit of each vertex, off depending on its height."""
    out = bytearray(data)
    streams = read_streams(data)
    colors, count, _ = streams[STREAM_COLOR]
    positions = streams[STREAM_POSITION][0]
    for i in range(count):
        index = colors + i * 4 + 3
        if is_off(struct.unpack_from("<f", data, positions + i * 12 + 8)[0]):
            out[index] &= ~(1 << bit) & 0xFF
        else:
            out[index] |= 1 << bit
    return bytes(out)


def equivalent_bones(source, bone_names):
    """Index in bone_names of each bone of source: the same name, or that of its first ancestor that is there."""
    result = {}
    for i, (name, _, parent) in enumerate(source):
        while name not in bone_names and parent >= 0:
            name, _, parent = source[parent]
        result[i] = bone_names.index(name) if name in bone_names else 0
    return result


def merge(data, other, bone_names):
    """Adds another mesh to one with a single subset. Its cloth comes from the BRAIES_UV patch, projected from the front."""
    streams = read_streams(data)
    extra = read_streams(other)
    vertices = streams[STREAM_POSITION][1]
    indices = streams[STREAM_INDICES][1]
    extra_vertices = extra[STREAM_POSITION][1]
    extra_indices = extra[STREAM_INDICES][1]
    points = [struct.unpack_from("<3f", other, extra[STREAM_POSITION][0] + i * 12) for i in range(extra_vertices)]
    minimum = [min(p[axis] for p in points) for axis in range(3)]
    maximum = [max(p[axis] for p in points) for axis in range(3)]
    u0, v0, u1, v1 = BRAIES_UV
    equivalent = equivalent_bones(bones(other), bone_names)
    other_chunks = {kind: (offset, size) for kind, _, _, size, offset in chunks(other)}
    entries = chunks(data)
    internal_count = (next(e[3] for e in entries if e[0] == CHUNK_VERTICES) - 32) // 64
    chunk_bodies = {}
    for entry in entries:
        kind, _, _, size, offset = entry
        body = bytearray(data[offset:offset + size])
        if kind == CHUNK_DATA_STREAM:
            _, stream, count, width = struct.unpack_from("<4I", data, offset)
            base, extra_count, extra_width = extra[stream]
            if width != extra_width:
                raise SystemExit(f"Stream {stream} differs when merging meshes")
            added = bytearray(other[base:base + extra_count * width])
            if stream == STREAM_INDICES:
                added = struct.pack(f"<{extra_count}H", *(v + vertices for v in struct.unpack(f"<{extra_count}H", added)))
            elif stream == STREAM_UV:
                for i, p in enumerate(points):
                    u = u0 + (p[0] - minimum[0]) / (maximum[0] - minimum[0]) * (u1 - u0)
                    v = v1 - (p[2] - minimum[2]) / (maximum[2] - minimum[2]) * (v1 - v0)
                    struct.pack_into("<2f", added, i * 8, u, v)
            elif stream == STREAM_WEIGHTS:
                for i in range(extra_count):
                    ids = struct.unpack_from("<4H", added, i * width)
                    struct.pack_into("<4H", added, i * width, *(equivalent[h] for h in ids))
            struct.pack_into("<I", body, 8, count + extra_count)
            body.extend(added)
        elif kind == CHUNK_MESH:
            struct.pack_into("<2I", body, 8, vertices + extra_vertices, indices + extra_indices)
            box = struct.unpack_from("<6f", body, 108)
            struct.pack_into("<6f", body, 108, *(min(box[e], minimum[e]) for e in range(3)), *(max(box[e + 3], maximum[e]) for e in range(3)))
        elif kind == CHUNK_SUBSETS:
            struct.pack_into("<I", body, 20, indices + extra_indices)
            struct.pack_into("<I", body, 28, vertices + extra_vertices)
        elif kind == CHUNK_VERTICES:
            base, extra_size = other_chunks[kind]
            added = bytearray(other[base + 32:base + extra_size])
            for i in range(len(added) // 64):
                ids = struct.unpack_from("<4H", added, i * 64 + 36)
                struct.pack_into("<4H", added, i * 64 + 36, *(equivalent[h] for h in ids))
            body.extend(added)
        elif kind in (CHUNK_FACES, CHUNK_EXT2INT):
            base, extra_size = other_chunks[kind]
            values = struct.unpack_from(f"<{extra_size // 2}H", other, base)
            body.extend(struct.pack(f"<{len(values)}H", *(v + internal_count for v in values)))
        chunk_bodies[entry] = bytes(body)
    return rebuild(entries, chunk_bodies)


def compact(data, triangles):
    """A mesh with only these vertices, without morphs: they index the whole mesh and the engine would write outside it."""
    entries = chunks(data)
    externals = sorted(set(triangles))
    new_external = {v: i for i, v in enumerate(externals)}
    ext2int = next(struct.unpack_from(f"<{size // 2}H", data, offset) for kind, _, _, size, offset in entries if kind == CHUNK_EXT2INT)
    internals = sorted({ext2int[v] for v in externals})
    new_internal = {v: i for i, v in enumerate(internals)}
    chunk_bodies = {}
    for entry in entries:
        kind, _, _, size, offset = entry
        body = bytearray(data[offset:offset + size])
        if kind == CHUNK_MORPHS:
            continue
        if kind == CHUNK_DATA_STREAM:
            _, stream, _, width = struct.unpack_from("<4I", data, offset)
            base = offset + 24
            if stream == STREAM_INDICES:
                struct.pack_into("<I", body, 8, len(triangles))
                stream_data = struct.pack(f"<{len(triangles)}{'H' if width == 2 else 'I'}", *(new_external[v] for v in triangles))
            else:
                struct.pack_into("<I", body, 8, len(externals))
                stream_data = b"".join(data[base + v * width:base + (v + 1) * width] for v in externals)
            body = body[:24] + stream_data
        elif kind == CHUNK_MESH:
            struct.pack_into("<2I", body, 8, len(externals), len(triangles))
            positions = read_streams(data)[STREAM_POSITION][0]
            points = [struct.unpack_from("<3f", data, positions + v * 12) for v in externals]
            struct.pack_into("<6f", body, 108, *(min(p[e] for p in points) for e in range(3)), *(max(p[e] for p in points) for e in range(3)))
        elif kind == CHUNK_SUBSETS:
            if struct.unpack_from("<I", body, 4)[0] != 1:
                raise SystemExit("Expected a single subset")
            struct.pack_into("<I", body, 20, len(triangles))
            struct.pack_into("<I", body, 28, len(externals))
        elif kind == CHUNK_VERTICES:
            body = body[:32] + b"".join(data[offset + 32 + v * 64:offset + 32 + (v + 1) * 64] for v in internals)
        elif kind == CHUNK_FACES:
            body = bytearray(struct.pack(f"<{len(triangles)}H", *(new_internal[ext2int[v]] for v in triangles)))
        elif kind == CHUNK_EXT2INT:
            body = bytearray(struct.pack(f"<{len(externals)}H", *(new_internal[ext2int[v]] for v in externals)))
        elif kind == CHUNK_BONE_BOXES:
            count = struct.unpack_from("<I", body, 28)[0]
            width = (size - 32) // count if count else 2
            indices = struct.unpack_from(f"<{count}{'H' if width == 2 else 'I'}", body, 32)
            alive = [new_external[v] for v in indices if v in new_external]
            body = body[:28] + struct.pack("<I", len(alive)) + struct.pack(f"<{len(alive)}{'H' if width == 2 else 'I'}", *alive)
        chunk_bodies[entry] = bytes(body)

    return rebuild(entries, chunk_bodies)


def add_morph(data, name, move_vertex):
    """Adds a morph to the whole mesh. move_vertex says how much each position moves.

    The morphs chunk is the count and, one after another, each morph: header, name, ranges of external vertices and 3
    bytes per external vertex, x, y, z, between the minimum and the maximum of the box.
    """
    entries = chunks(data)
    positions, external_count, _ = read_streams(data)[STREAM_POSITION]
    internal_count = next((size - 32) // 64 for kind, _, _, size, _ in entries if kind == CHUNK_VERTICES)
    movements = [move_vertex(struct.unpack_from("<3f", data, positions + i * 12)) for i in range(external_count)]
    minimum = [min(m[axis] for m in movements) for axis in range(3)]
    maximum = [max(max(m[axis] for m in movements), minimum[axis] + 1e-4) for axis in range(3)]
    max_length = max(sum(x * x for x in m) ** 0.5 for m in movements)
    text = name.encode() + bytes(1)
    morph = (struct.pack("<iIII6fIf", -1, len(text), internal_count, external_count, *minimum, *maximum, 1, max_length)
             + text + struct.pack("<2H", 0, external_count)
             + bytes(round((m[axis] - minimum[axis]) / (maximum[axis] - minimum[axis]) * 255) for m in movements for axis in range(3)))
    chunk_bodies = {entry: data[entry[4]:entry[4] + entry[3]] for entry in entries}
    chunk = next((e for e in entries if e[0] == CHUNK_MORPHS), None)
    if chunk:
        chunk_bodies[chunk] = struct.pack("<I", struct.unpack_from("<I", data, chunk[4])[0] + 1) + chunk_bodies[chunk][4:] + morph
        return rebuild(entries, chunk_bodies)
    vertices = next(e for e in entries if e[0] == CHUNK_VERTICES)
    new_entry = (CHUNK_MORPHS, MORPHS_VERSION, max(e[2] for e in entries) + 1, 0, vertices[4] - 1)
    chunk_bodies[new_entry] = struct.pack("<I", 1) + morph
    return rebuild(entries + [new_entry], chunk_bodies)


def between(value, start, end):
    """From 0 at start to 1 at end."""
    return min(max((value - start) / (end - start), 0), 1)


def above_neck(point):
    """From 0 at the shoulders of the hood to 1 at the head."""
    return between(point[2], HOOD_SHOULDER, HOOD_NECK)


def fit_cape(point):
    cape = 1 - above_neck(point)
    lower = between(abs(point[0]), *SHOULDER_X) * between(abs(point[1] - SHOULDER_CENTER), *SHOULDER_Y)
    return (-point[0] * NARROW_CAPE * cape, -point[1] * NARROW_CAPE * cape, -LOWER_CAPE * lower * cape)


def headgear_morphs(data, path):
    """The headgear goes down whole. The hood, only from the neck up. The collar does not go down: it rests on the shoulders."""
    if "/collar/" in path:
        return add_morph(data, DRESS_MORPH, lambda p: (-p[0] * NARROW_COLLAR, -p[1] * NARROW_COLLAR, 0.0))
    if "/hood/" not in path:
        return add_morph(data, HEAD_MORPH, lambda p: HEADGEAR_OFFSET)
    data = add_morph(data, HEAD_MORPH, lambda p: tuple(x * above_neck(p) for x in HEADGEAR_OFFSET))
    return add_morph(data, DRESS_MORPH, fit_cape)


def weight_like_skirt(data, man):
    """The braies move with the skirt that covers them. With their own weights they follow the thigh fully, and go through
    the skirt when walking."""
    out = bytearray(data)
    bone_names = [name for name, _, _ in bones(data)]
    streams = read_streams(data)
    positions, count, _ = streams[STREAM_POSITION]
    bone_map, _, width = streams[STREAM_WEIGHTS]
    for i in range(count):
        result = skirt_weight(struct.unpack_from("<3f", data, positions + i * 12), bone_names, man)
        ints = [round(weight * 255) for _, weight in result]
        ints[0] += 255 - sum(ints)
        struct.pack_into("<4H4B", out, bone_map + i * width, *(bone for bone, _ in result), *ints)
    for kind, _, _, size, offset in chunks(data):
        if kind == CHUNK_VERTICES:
            for i in range((size - 32) // 64):
                base = offset + 32 + i * 64
                result = skirt_weight(struct.unpack_from("<3f", data, base + 12), bone_names, man)
                struct.pack_into("<4H4f", out, base + 36, *(bone for bone, _ in result), *(weight for _, weight in result))
    return bytes(out)


def fit_braies(data):
    """The man's braies, inside the smock: without the waist, and narrower at the hips."""
    positions, count, _ = read_streams(data)[STREAM_POSITION]
    indices, total, _ = read_streams(data)[STREAM_INDICES]
    heights = [struct.unpack_from("<f", data, positions + i * 12 + 8)[0] for i in range(count)]
    vertices = struct.unpack_from(f"<{total}H", data, indices)
    triangles = []
    for t in range(0, total, 3):
        if max(heights[v] for v in vertices[t:t + 3]) <= BRAIES_CUT:
            triangles.extend(vertices[t:t + 3])
    out = bytearray(compact(data, triangles))

    def narrow(base):
        x, y, z = struct.unpack_from("<3f", out, base)
        factor = 1 - (1 - BRAIES_HIP) * min(max((z - BRAIES_START) / (BRAIES_END - BRAIES_START), 0), 1)
        struct.pack_into("<2f", out, base, x * factor, AXIS_Y + (y - AXIS_Y) * factor)

    positions, count, _ = read_streams(out)[STREAM_POSITION]
    for i in range(count):
        narrow(positions + i * 12)
    for kind, _, _, size, offset in chunks(out):
        if kind == CHUNK_VERTICES:
            for i in range((size - 32) // 64):
                narrow(offset + 32 + i * 64 + 12)
    return bytes(out)


def split_mesh(data, per_vertex, order, choose=None):
    """Each triangle goes to the part of most of its vertices, unless choose says otherwise."""
    choose = choose or (lambda votes: max(order, key=votes.count))
    indices, total, width = read_streams(data)[STREAM_INDICES]
    fmt = "<3H" if width == 2 else "<3I"
    triangles = {part: [] for part in order}
    for t in range(0, total, 3):
        vertices = struct.unpack_from(fmt, data, indices + t * width)
        triangles[choose([per_vertex[v] for v in vertices])].extend(vertices)
    return {part: compact(data, part_triangles) for part, part_triangles in triangles.items()}


def generate_meshes():
    index = {}
    paks = [*(GAME / "Data").glob("*Characters*.pak"), *(GAME / "Data").glob("*Heads*.pak")]
    for pak in sorted(paks):
        with zipfile.ZipFile(pak) as archive:
            for name in archive.namelist():
                normalized = name.replace("\\", "/").lower()
                if normalized.startswith(GAME_PATH) and normalized.endswith((".skin", ".chr")):
                    index[normalized] = (pak, name)

    def read(normalized):
        pak, name = index[normalized]
        with zipfile.ZipFile(pak) as archive:
            return archive.read(name)

    def bone_positions(gender):
        return {n: p for n, p, _ in bones(read(f"{GAME_PATH}{gender}/skeleton/{gender}.chr"))}

    man, woman = bone_positions("male"), bone_positions("female")
    for kind, path in sorted(meshes):
        source = f"{GAME_PATH}female/{kind}/{path}".lower()
        if source not in index:
            raise SystemExit(f"Not in the paks: {source}")
        base = source[:-len(".skin")]
        for name in sorted(n for n in index if n == source or n.startswith(base + "_lod")):
            file_name = pathlib.PurePosixPath(name).name
            skirt = SMOCK_SKIRT if file_name.startswith(SMOCK) else DRESS_SKIRT if "_waist" in file_name else 0
            fitted, low, high = fit(read(name), man, woman, hidden(kind, path), skirt)
            out_path = MESHES_DIR / kind / pathlib.PurePosixPath(path).parent / file_name
            out_path.parent.mkdir(parents=True, exist_ok=True)
            print(f"{out_path.name}: height {low:.3f} to {high:.3f}")
            mesh_stem = pathlib.PurePosixPath(path).stem.lower()
            if kind == "body":
                parts = split_mesh(fitted, parts_by_bone(fitted), list(BODY_PARTS))
                for bit in (THIGHS_BIT, UNDER_WAIST_BIT):
                    parts["legs"] = mark_bit(parts["legs"], bit, lambda height: height >= THIGHS_HEIGHT)
            elif mesh_stem == SMOCK:
                body = read(GAME_PATH + BASE_BODY)
                # The edge follows a line of the mesh: splitting by majority leaves it jagged.
                parts = split_mesh(without_cloth(fitted, body, man), parts_by_height(fitted), list(SMOCK_PARTS),
                                   lambda votes: "skirt" if "skirt" in votes else "top")

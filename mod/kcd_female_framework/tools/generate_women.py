def write_table(target, list_tag, rows, version=1):
    target.parent.mkdir(parents=True, exist_ok=True)
    body = "".join(f"\t\t{ET.tostring(row, encoding='unicode')}\n" for row in rows)
    target.write_text('<?xml version="1.0" encoding="utf-8"?>\n<database xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" '
                      f'name="barbora" xsi:noNamespaceSchemaLocation="../database.xsd">\n\t<{list_tag} version="{version}">\n{body}'
                      f"\t</{list_tag}>\n</database>\n", encoding="utf-8")


def buff_row(name, seed, **extra):
    guid = str(uuid.uuid5(uuid.NAMESPACE_URL, f"{GUID_NAMESPACE}/{seed}"))
    return guid, ET.Element("buff", {
        **extra, "buff_class_id": "12", "buff_exclusivity_id": "1", "buff_id": guid, "buff_lifetime_id": "0",
        "buff_name": name, "buff_params": "charisma+0", "duration": "-1",
        "implementation": "Cpp:EquippableItemWeighted", "is_persistent": "true",
    })


def write_detection():
    """The tags and the valueless effects of the women's clothes. The armor_type rows go complete."""
    vanilla = ET.parse(TABLES / "item/armor_type.xml").getroot().find("armor_types")
    ai_tags, buffs, armor_types = [], [buff_row(OLD_BUFF, OLD_BUFF_SEED)[1]], []
    for group, (ai_tag, names) in DETECTED_CLOTHES.items():
        name = f"{PREFIX}{group}"
        guid, row = buff_row(name, f"{GUID_PREFIX}woman_{group}", buff_ai_tag_id=str(ai_tag))
        buffs.append(row)
        ai_tags.append(ET.Element("buff_ai_tag", {"buff_ai_tag_id": str(ai_tag), "buff_ai_tag_name": name}))
        for type_name in names:
            type_row = next(f for f in vanilla if f.get("Name") == type_name)
            armor_types.append(ET.Element("armor_type", {**type_row.attrib, "EquipBuffId": guid}))
    write_table(MOD_TABLES / f"item/armor_type__{MOD}.xml", "armor_types", armor_types)
    write_table(MOD_TABLES / f"rpg/buff__{MOD}.xml", "buffs", buffs)
    write_table(MOD_TABLES / f"rpg/buff_ai_tag__{MOD}.xml", "buff_ai_tags", ai_tags)
